export function zhText(value?: string | null) {
  if (!value) return value
  return textMap[value] ?? value
}

export function zhErrorText(value?: string | null) {
  if (!value) return value
  if (textMap[value]) return textMap[value]
  return value
    .replace(/^The (.+) field is required\.$/, '请填写$1。')
    .replace(/^The (.+) must be a valid email address\.$/, '$1格式不正确。')
    .replace(/^The (.+) must be at least (\d+) characters\.$/, '$1至少需要$2个字符。')
    .replace(/^The (.+) must not be greater than (\d+) characters\.$/, '$1不能超过$2个字符。')
    .replace(/^The selected (.+) is invalid\.$/, '选择的$1无效。')
    .replace(/^The (.+) must be an integer\.$/, '$1必须是整数。')
    .replace(/^The (.+) field must be true or false\.$/, '$1必须为是或否。')
    .replace(/^The (.+) must be an array\.$/, '$1必须是数组。')
    .replace(/^The (.+) has already been taken\.$/, '$1已存在。')
}

const attrNames = ['placeholder', 'aria-label', 'title'] as const

function translateNodeText(node: Node) {
  if (node.nodeType !== Node.TEXT_NODE || !node.textContent) return
  const raw = node.textContent
  const trimmed = raw.trim()
  const translated = textMap[trimmed]
  if (!translated) return
  node.textContent = raw.replace(trimmed, translated)
}

function translateAttributes(element: Element) {
  for (const attr of attrNames) {
    const value = element.getAttribute(attr)
    if (value && textMap[value]) element.setAttribute(attr, textMap[value])
  }
}

function translateTree(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    translateNodeText(node)
    node = walker.nextNode()
  }
  if (root instanceof Element) translateAttributes(root)
  root.querySelectorAll?.('*').forEach(translateAttributes)
}

let installed = false

export function installChineseUiTranslations() {
  if (installed || typeof document === 'undefined') return
  installed = true
  const run = () => translateTree(document.body)
  run()
  new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) translateNodeText(node)
        if (node instanceof Element) translateTree(node)
      })
      if (mutation.type === 'characterData') translateNodeText(mutation.target)
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true })
}
